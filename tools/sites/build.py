"""Builds lib/sites.js from the merged research (merge.py -> merged.json).

Run from the repo root:
    python3 tools/sites/merge.py tools/sites/research
    python3 tools/sites/build.py tools/sites/research/merged.json lib/sites.js

Category merges and renames agreed with the founder on 2026-10-15 live here, so
the research files stay as the researchers wrote them.
"""
import json, sys

MERGE = {
    'Email': 'Email & calendar', 'Calendar': 'Email & calendar',
    'Chat': 'Chat & calls', 'Meetings': 'Chat & calls',
    'Maps': 'Travel', 'Weather': 'News', 'Real estate': 'Shopping',
    'Development': 'Coding', 'Work tools': 'Work',
}

merged = json.load(open(sys.argv[1]))['rules']
rules = []
for r in merged:
    cat = MERGE.get(r['category'], r['category'])
    rules.append((r['host'], r['path'], r['query'], cat))
cats = sorted({r[3] for r in rules})
index = {c: i for i, c in enumerate(cats)}
rows = sorted(rules)

with open(sys.argv[2], 'w') as f:
    f.write('// GENERATED by tools/sites/build.py from tools/sites/research. Do not edit by hand.\n')
    f.write('// Known sites and web-app addresses, mapped to the use-case group their tabs go in.\n')
    f.write('// Each rule: [host, pathPrefix, queryContains, categoryIndex]. A host starting\n')
    f.write('// with "*." matches every subdomain of what follows.\n\n')
    f.write('export const CATEGORIES = ' + json.dumps(cats) + ';\n\n')
    f.write('export const SITE_RULES = [\n')
    for h, p, q, c in rows:
        f.write('  ' + json.dumps([h, p, q, index[c]], separators=(',', ':')) + ',\n')
    f.write('];\n')
print(len(rows), 'rules,', len(cats), 'categories:', ', '.join(cats))
